import 'package:flutter/material.dart';
import 'package:supabase_flutter/supabase_flutter.dart' as supa;
import '../models/models.dart';

class StudentController extends ChangeNotifier {
  List<Student> _students = [];
  List<Student> get students => _students;

  bool _isLoading = false;
  bool get isLoading => _isLoading;

  final client = supa.Supabase.instance.client;

  Future<void> loadStudents() async {
    _isLoading = true;
    notifyListeners();

    final response = await client.from('estudiantes').select();
    _students = response.map((map) => Student.fromMap(map)).toList();
    
    _isLoading = false;
    notifyListeners();
  }

  Future<void> addStudent(Student student) async {
    final map = student.toMap();
    map.remove('id'); // ID is generated by Supabase
    await client.from('estudiantes').insert(map);
    await loadStudents();
  }

  Future<void> updateStudent(Student student) async {
    final map = student.toMap();
    map.remove('id');
    await client.from('estudiantes').update(map).eq('id', student.id!);
    await loadStudents();
  }

  Future<void> deleteStudent(int id) async {
    await client.from('estudiantes').delete().eq('id', id);
    await loadStudents();
  }
}
